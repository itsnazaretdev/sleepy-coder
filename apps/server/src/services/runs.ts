import { rm } from 'node:fs/promises';
import { join } from 'node:path';
import { executeTask, type AgentModel } from '@sleepy-coder/agent';
import { analyzeStructure } from '@sleepy-coder/analyzer';
import { removeTaskWorktree } from '@sleepy-coder/git';
import type { OllamaClient } from '@sleepy-coder/ollama';
import type { Task, TaskRun } from '@sleepy-coder/shared';
import { huntStaticTasks } from '@sleepy-coder/tasks';
import type { RunStore } from '../store/runs.js';
import { hashFingerprint } from '../store/tasks.js';
import { requireModel } from './ollama.js';
import { RepositoryError, resolveRepositoryPath } from './repositories.js';
import { TaskNotFoundError, type TaskDeps } from './tasks.js';

export interface RunDeps extends TaskDeps {
  runs: RunStore;
  ollama: OllamaClient;
  configuredModel: string | null;
  /** Folder for agent worktrees, inside Sleepy Coder's data folder. */
  worktreesDir: string;
  /** Injected in tests instead of Ollama. */
  agentModel?: AgentModel;
  /** The autonomous agent is experimental: off unless SLEEPY_EXPERIMENTAL_AGENT=1 (ADR-023). */
  experimentalAgent: boolean;
}

export class AgentDisabledError extends Error {
  constructor() {
    super('The autonomous agent is experimental and turned off. Start the backend with SLEEPY_EXPERIMENTAL_AGENT=1 to use it.');
    this.name = 'AgentDisabledError';
  }
}

export class TaskNotApprovedError extends Error {
  constructor() {
    super('Only approved tasks can be run. Approve the task first.');
    this.name = 'TaskNotApprovedError';
  }
}

export class AgentBusyError extends Error {
  constructor() {
    super('The agent is already working on another task. Wait for it to finish.');
    this.name = 'AgentBusyError';
  }
}

export class RunNotFoundError extends Error {
  constructor(id: string) {
    super(`Unknown run: ${id}`);
    this.name = 'RunNotFoundError';
  }
}

/** Editing whole files needs more context than suggesting tasks. */
const AGENT_CONTEXT_TOKENS = 16_384;
const AGENT_TIMEOUT_MS = 300_000;

function ollamaAgentModel(client: OllamaClient, model: string): AgentModel {
  return {
    async complete(messages, schema) {
      const result = await client.chat({
        model,
        messages,
        format: schema,
        temperature: 0.2,
        numCtx: AGENT_CONTEXT_TOKENS,
        timeoutMs: AGENT_TIMEOUT_MS,
      });
      return result.content;
    },
  };
}

/**
 * For tasks found by rules (TODO, duplicate <h1>, missing alt, LICENSE…), the same rules are run
 * again on the agent's worktree: if they still produce this task, the task is not solved.
 * AI-suggested tasks have no rule to check, so they get no verification.
 */
export function staticTaskVerifier(task: Task): ((worktreePath: string) => Promise<string | null>) | undefined {
  if (task.source !== 'static') return undefined;
  return async (worktreePath) => {
    const { drafts } = await huntStaticTasks(worktreePath);
    const still = drafts.find((draft) => hashFingerprint(draft.fingerprint) === task.fingerprint);
    return still ? still.description : null;
  };
}

/** One run at a time: the local model and the tests both need the machine's resources. */
let activeRunId: string | null = null;

export function isAgentBusy(): boolean {
  return activeRunId !== null;
}

/** Worktree folder for a run. Ids are generated by us, never taken from the request. */
const worktreePathFor = (deps: RunDeps, repositoryId: string, runId: string) =>
  join(deps.worktreesDir, repositoryId, runId);

/**
 * Starts the agent on an approved task, in the background.
 * Returns the new run immediately (status "running") and a promise that resolves when it ends.
 */
export async function startRun(taskId: string, deps: RunDeps): Promise<{ run: TaskRun; finished: Promise<TaskRun> }> {
  if (!deps.experimentalAgent) throw new AgentDisabledError();
  if (activeRunId) throw new AgentBusyError();

  const task = deps.tasks.get(taskId);
  if (!task) throw new TaskNotFoundError(taskId);
  if (task.status !== 'approved') throw new TaskNotApprovedError();

  const repository = await deps.store.get(task.repositoryId);
  if (!repository) throw new RepositoryError('repository-not-found', `Unknown repository: ${task.repositoryId}`);
  await resolveRepositoryPath(repository.path, deps);

  const model = deps.agentModel ?? ollamaAgentModel(deps.ollama, await requireModel(deps.ollama, deps.configuredModel));

  // Check again: another request may have started a run while we were checking.
  if (activeRunId) throw new AgentBusyError();
  const run = deps.runs.create(task.id, repository.id);
  activeRunId = run.id;

  const finished = (async (): Promise<TaskRun> => {
    try {
      const { testingTools } = await analyzeStructure(repository.path);
      const outcome = await executeTask({
        task,
        repoPath: repository.path,
        worktreePath: worktreePathFor(deps, repository.id, run.id),
        model,
        testingTools,
        verify: staticTaskVerifier(task),
        onStep: (message) => deps.runs.addStep(run.id, message),
      });

      return deps.runs.update(run.id, {
        status: outcome.status,
        branch: outcome.branch,
        baseCommit: outcome.baseCommit,
        commit: outcome.commit,
        summary: outcome.summary,
        files: outcome.files,
        diff: outcome.diff,
        testsBefore: outcome.testsBefore,
        testsAfter: outcome.testsAfter,
        error: outcome.error,
        finishedAt: new Date().toISOString(),
      }) as TaskRun;
    } catch (error) {
      // executeTask reports its own errors; this only catches unexpected ones.
      return deps.runs.update(run.id, {
        status: 'failed',
        error: error instanceof Error ? error.message : String(error),
        finishedAt: new Date().toISOString(),
      }) as TaskRun;
    } finally {
      activeRunId = null;
    }
  })();

  return { run, finished };
}

export function getRun(id: string, deps: RunDeps): TaskRun {
  const run = deps.runs.get(id);
  if (!run) throw new RunNotFoundError(id);
  return run;
}

export async function listLatestRuns(repositoryId: string, deps: RunDeps): Promise<TaskRun[]> {
  if (!(await deps.store.get(repositoryId))) {
    throw new RepositoryError('repository-not-found', `Unknown repository: ${repositoryId}`);
  }
  return deps.runs.latestByRepository(repositoryId);
}

/**
 * At startup: runs left "running" by a previous backend are marked "interrupted" and their
 * worktree folders removed. Nothing is resumed automatically.
 */
export async function recoverInterruptedRuns(deps: RunDeps): Promise<TaskRun[]> {
  const interrupted = deps.runs.interruptRunning();

  for (const run of interrupted) {
    const path = worktreePathFor(deps, run.repositoryId, run.id);
    const repository = await deps.store.get(run.repositoryId);
    if (repository) await removeTaskWorktree(repository.path, path).catch(() => undefined);
    await rm(path, { recursive: true, force: true }).catch(() => undefined);
  }

  return interrupted;
}
